import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

/**
 * Builds a single-file executable from the Nitro server.
 *
 * - loads key/value pairs from .env before building (so build tools see them)
 * - builds Nitro with the `bun` preset
 * - compiles .output/server/index.mjs into one standalone binary in dist/
 *
 * Optional environment variables:
 *   BINARY_TARGET   Bun compile target, e.g. `bun-windows-x64`, `bun-linux-x64`,
 *                   `bun-darwin-arm64`. Defaults to the current platform.
 *   BINARY_NAME     Output file name (default: `outpost`).
 */

function loadEnvFile(path: string): void {
  let contents: string;
  try {
    contents = readFileSync(path, "utf8");
  } catch {
    return;
  }

  for (const rawLine of contents.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const separator = line.indexOf("=");
    if (separator < 0) continue;

    const key = line
      .slice(0, separator)
      .trim()
      .replace(/^export\s+/, "");
    if (!key) continue;

    let value = line.slice(separator + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    // Real environment variables take precedence over the .env file.
    if (process.env[key] === undefined) process.env[key] = value;
  }
}

function run(command: string, args: string[]): void {
  console.log(`\n> ${command} ${args.join(" ")}`);
  const result = spawnSync(command, args, { stdio: "inherit", shell: false });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
}

loadEnvFile(resolve(process.cwd(), ".env"));

// Nitro's bun preset emits an entry point that Bun can bundle into one file.
process.env.NITRO_PRESET = "bun";

run("bun", ["x", "nitro", "build"]);

const outputName = process.env.BINARY_NAME || "outpost";

// Bun's `--env` only accepts one prefix, so bake the app's configuration by
// generating a tiny entry point that assigns values from .env before the
// Nitro server loads. PORT/HOST remain runtime-overridable.
const bakedKeys = [
  "DB_FILE_NAME",
  "BETTER_AUTH_SECRET",
  "BETTER_AUTH_URL",
  "MCP_RESOURCE_URL",
];
const bakedValues: Record<string, string> = {};
for (const key of bakedKeys) {
  if (process.env[key] !== undefined) bakedValues[key] = process.env[key]!;
}

const entryPath = resolve(process.cwd(), ".binary-entry.ts");
writeFileSync(
  entryPath,
  `// Generated by scripts/build-binary.ts — do not edit.\n` +
    `Object.assign(process.env, ${JSON.stringify(bakedValues)});\n` +
    `await import("./.output/server/index.mjs");\n`,
);

const compileArgs = [
  "build",
  "--compile",
  ".binary-entry.ts",
  "--outfile",
  `dist/${outputName}`,
  // Keep the binary self-contained: no .env lookup at runtime.
  "--no-compile-autoload-dotenv",
];
if (process.env.BINARY_TARGET)
  compileArgs.push(`--target=${process.env.BINARY_TARGET}`);

run("bun", compileArgs);
console.log(`\nBinary written to dist/${outputName}`);
